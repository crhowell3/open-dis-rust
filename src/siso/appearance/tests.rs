#[test]
fn undefined_values_read_as_none() {
    // Bits 9-11 hold 7; UID 382 stops at 5.
    assert_eq!(
        LandPlatformAppearance::from_raw(0b111 << 9).primary_hatch(),
        None
    );
    // Bits 9-11 hold 2; UID 388 defines 0, 1 and 4.
    assert_eq!(SubsurfacePlatformAppearance::from_raw(2 << 9).hatch(), None);
}

fn entity(kind: EntityKind, domain: u8, category: u8) -> EntityType {
    EntityType::new(kind, domain, Country::Other, category, 0, 0, 0)
}

#[test]
fn view_picks_the_layout_from_the_entity_type() {
    let a = EntityAppearance::from_raw(0x1234_5678);
    let cases = [
        (
            entity(EntityKind::Platform, 1, 0),
            AppearanceView::LandPlatform(a.into()),
        ),
        (
            entity(EntityKind::Platform, 2, 0),
            AppearanceView::AirPlatform(a.into()),
        ),
        (
            entity(EntityKind::Platform, 3, 0),
            AppearanceView::SurfacePlatform(a.into()),
        ),
        (
            entity(EntityKind::Platform, 4, 0),
            AppearanceView::SubsurfacePlatform(a.into()),
        ),
        (
            entity(EntityKind::Platform, 5, 0),
            AppearanceView::SpacePlatform(a.into()),
        ),
        (
            entity(EntityKind::Munition, 1, 0),
            AppearanceView::Munition(a.into()),
        ),
        (
            entity(EntityKind::LifeForm, 1, 130),
            AppearanceView::HumanLifeForm(a.into()),
        ),
        (
            entity(EntityKind::LifeForm, 1, 200),
            AppearanceView::NonHumanLifeForm(a.into()),
        ),
        (
            entity(EntityKind::Environmental, 0, 0),
            AppearanceView::Environmental(a.into()),
        ),
        (
            entity(EntityKind::CulturalFeature, 0, 0),
            AppearanceView::CulturalFeature(a.into()),
        ),
        (
            entity(EntityKind::Supply, 0, 0),
            AppearanceView::Supply(a.into()),
        ),
        (
            entity(EntityKind::Radio, 0, 0),
            AppearanceView::Radio(a.into()),
        ),
        (
            entity(EntityKind::Expendable, 0, 0),
            AppearanceView::Expendable(a.into()),
        ),
        (
            entity(EntityKind::SensorEmitter, 0, 0),
            AppearanceView::SensorEmitter(a.into()),
        ),
    ];
    for (entity_type, expected) in cases {
        let view = a.view(&entity_type);
        assert_eq!(view, Some(expected), "{entity_type:?}");
        assert_eq!(
            view.map(EntityAppearance::from),
            Some(a),
            "bits are unchanged"
        );
    }
    assert_eq!(a.view(&entity(EntityKind::Other, 0, 0)), None);
    assert_eq!(a.view(&entity(EntityKind::Platform, 6, 0)), None);
}
